"""
export_urdf.py -- `ros2 run QuadPkg export_urdf [output.urdf]`

Writes ONE URDF file = robot (zero = standing) + everything in config/payload.yaml,
with absolute mesh paths, ready for Isaac Sim's URDF importer.

Re-run it (and re-import in Isaac) whenever you change payload.yaml.

Options
  output path       default: ./QuadRobot_with_payload.urdf
  --urdf PATH       robot URDF   (default: installed QuadURDFcad4_0.urdf)
  --payload PATH    payload yaml (default: installed config/payload.yaml, "" = none)
"""
import argparse
import os

from QuadPkg.description.robot_description import load_robot_xml, mass_report
from QuadPkg.kinematics.leg_kinematics import QuadKinematics


def main(args=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("output", nargs="?", default="QuadRobot_with_payload.urdf")
    ap.add_argument("--urdf", default=None)
    ap.add_argument("--payload", default=None)
    a, _ = ap.parse_known_args(args)

    xml = load_robot_xml(a.urdf, a.payload, absolute_meshes=True)
    with open(a.output, "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n')
        f.write("<!-- GENERATED by `ros2 run QuadPkg export_urdf` -- do not edit, edit config/payload.yaml -->\n")
        f.write(xml)
    print(f"wrote {os.path.abspath(a.output)}")
    print(mass_report(QuadKinematics(xml)))


if __name__ == "__main__":
    main()
